#!/usr/bin/env python3
"""Makes cp400_chargen.vhd (the MC6847 character generator, 2048 x 8, inferred ROM) from an Intel HEX file
(CP400_COLOR_FPGA/FPGA/src/plataform/roms/mc6847_ntsc.hex): python gen_chargen.py mc6847_ntsc.hex"""
import sys

data = bytearray(2048)
for line in open(sys.argv[1]):
    line = line.strip()
    if not line.startswith(":"):
        continue
    n = int(line[1:3], 16); a = int(line[3:7], 16); t = int(line[7:9], 16)
    if t == 0:
        data[a:a + n] = bytes.fromhex(line[9:9 + 2 * n])
rows = ",\n".join("\t\t" + ", ".join('x"%02X"' % b for b in data[i:i + 8]) for i in range(0, 2048, 8))
open("cp400_chargen.vhd", "w").write("""-- MC6847 character generator ROM of the CP-400 core (generated by gen_chargen.py from mc6847_ntsc.hex).
-- Replaces the Altera altsyncram ROM (sprom) of the original: a plain inferred ROM.
library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;

entity cp400_chargen is
	port (
		clock   : in  std_logic;
		address : in  std_logic_vector(10 downto 0);
		q       : out std_logic_vector(7 downto 0)
	);
end cp400_chargen;

architecture rtl of cp400_chargen is
	type rom_t is array (0 to 2047) of std_logic_vector(7 downto 0);
	constant rom : rom_t := (
%s
	);
begin
	process (clock)
	begin
		if rising_edge(clock) then
			q <= rom(to_integer(unsigned(address)));
		end if;
	end process;
end rtl;
""" % rows)
